CREATE TABLE IF NOT EXISTS users (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('ADMIN','LOGISTICS_OFFICER','REQUESTER')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE IF NOT EXISTS personnel (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         employee_code VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(150) NOT NULL,
    role VARCHAR(100) NOT NULL,
    unit_name VARCHAR(100) NOT NULL,
    posting VARCHAR(150),
    availability_status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
    CHECK (availability_status IN ('AVAILABLE','ALLOCATED','UNAVAILABLE')),
    active BOOLEAN NOT NULL DEFAULT TRUE
    );

CREATE TABLE IF NOT EXISTS vehicles (
                                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        registration_no VARCHAR(50) NOT NULL UNIQUE,
    vehicle_type VARCHAR(80) NOT NULL,
    driver_id BIGINT,
    location VARCHAR(150),
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'
    CHECK (status IN ('AVAILABLE','ALLOCATED','UNAVAILABLE','UNDER_MAINTENANCE')),
    condition_status VARCHAR(30) NOT NULL DEFAULT 'OPERATIONAL'
    CHECK (condition_status IN ('OPERATIONAL','NEEDS_REPAIR','UNSERVICEABLE')),
    CONSTRAINT fk_vehicles_driver FOREIGN KEY (driver_id)
    REFERENCES personnel(id) ON UPDATE CASCADE ON DELETE SET NULL
    );

CREATE TABLE IF NOT EXISTS equipment (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         asset_code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    category VARCHAR(80),
    location VARCHAR(150),
    ownership_unit VARCHAR(100),
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE'
    CHECK (status IN ('AVAILABLE','ALLOCATED','UNAVAILABLE','UNDER_MAINTENANCE')),
    condition_status VARCHAR(30) NOT NULL DEFAULT 'OPERATIONAL'
    CHECK (condition_status IN ('OPERATIONAL','NEEDS_REPAIR','UNSERVICEABLE'))
    );

CREATE TABLE IF NOT EXISTS logistics_requests (
                                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  request_number VARCHAR(50) NOT NULL UNIQUE,
    requested_by BIGINT NOT NULL,
    requesting_unit VARCHAR(100) NOT NULL,
    purpose TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
    CHECK (status IN ('PENDING','APPROVED','REJECTED','ALLOCATED','IN_PROGRESS','COMPLETED','CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_requests_requester FOREIGN KEY (requested_by)
    REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT
    );

CREATE TABLE IF NOT EXISTS request_items (
                                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                             request_id BIGINT NOT NULL,
                                             resource_type VARCHAR(20) NOT NULL
    CHECK (resource_type IN ('PERSONNEL','VEHICLE','EQUIPMENT','SUPPLY')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    description TEXT NOT NULL,
    CONSTRAINT fk_request_items_request FOREIGN KEY (request_id)
    REFERENCES logistics_requests(id) ON UPDATE CASCADE ON DELETE CASCADE
    );

CREATE TABLE IF NOT EXISTS allocations (
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                           request_id BIGINT NOT NULL,
                                           resource_type VARCHAR(20) NOT NULL
    CHECK (resource_type IN ('PERSONNEL','VEHICLE','EQUIPMENT')),
    resource_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
    CHECK (status IN ('ACTIVE','RELEASED','CANCELLED')),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMPTZ,
    CONSTRAINT fk_allocations_request FOREIGN KEY (request_id)
    REFERENCES logistics_requests(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_allocation_release_time
    CHECK (released_at IS NULL OR released_at >= assigned_at)
    );

CREATE TABLE IF NOT EXISTS request_history (
                                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               request_id BIGINT NOT NULL,
                                               changed_by BIGINT,
                                               old_status VARCHAR(30),
    new_status VARCHAR(30) NOT NULL
    CHECK (new_status IN ('PENDING','APPROVED','REJECTED','ALLOCATED','IN_PROGRESS','COMPLETED','CANCELLED')),
    remarks TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_request_history_request FOREIGN KEY (request_id)
    REFERENCES logistics_requests(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_request_history_user FOREIGN KEY (changed_by)
    REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT chk_history_old_status CHECK (old_status IS NULL OR old_status IN
('PENDING','APPROVED','REJECTED','ALLOCATED','IN_PROGRESS','COMPLETED','CANCELLED'))
    );

CREATE TABLE IF NOT EXISTS inventory (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         item_code VARCHAR(50) NOT NULL UNIQUE,
    item_name VARCHAR(150) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE IF NOT EXISTS inventory_issues (
                                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                inventory_id BIGINT NOT NULL,
                                                request_id BIGINT NOT NULL,
                                                quantity INTEGER NOT NULL CHECK (quantity > 0),
    issued_by BIGINT NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_inventory_issues_inventory FOREIGN KEY (inventory_id)
    REFERENCES inventory(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_issues_request FOREIGN KEY (request_id)
    REFERENCES logistics_requests(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_issues_user FOREIGN KEY (issued_by)
    REFERENCES users(id) ON UPDATE CASCADE ON DELETE RESTRICT
    );

CREATE TABLE IF NOT EXISTS maintenance_records (
                                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                   resource_type VARCHAR(20) NOT NULL CHECK (resource_type IN ('VEHICLE','EQUIPMENT')),
    resource_id BIGINT NOT NULL,
    maintenance_type VARCHAR(20) NOT NULL CHECK (maintenance_type IN ('PREVENTIVE','CORRECTIVE')),
    description TEXT NOT NULL,
    scheduled_date DATE NOT NULL,
    completed_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
    CHECK (status IN ('SCHEDULED','IN_PROGRESS','COMPLETED','CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_maintenance_completion_date
    CHECK (completed_date IS NULL OR completed_date >= scheduled_date)
    );

CREATE TABLE IF NOT EXISTS drivers (
                                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       name VARCHAR(100) NOT NULL,
    license_number VARCHAR(50) NOT NULL UNIQUE,
    contact_number VARCHAR(20),
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    assigned_vehicle_id BIGINT,
    active BOOLEAN NOT NULL DEFAULT TRUE
    );

CREATE INDEX IF NOT EXISTS idx_requests_status ON logistics_requests(status);
CREATE INDEX IF NOT EXISTS idx_requests_created_at ON logistics_requests(created_at);
CREATE INDEX IF NOT EXISTS idx_vehicle_status ON vehicles(status);
CREATE INDEX IF NOT EXISTS idx_equipment_status ON equipment(status);
CREATE INDEX IF NOT EXISTS idx_personnel_availability ON personnel(availability_status);
CREATE INDEX IF NOT EXISTS idx_allocations_request_status ON allocations(request_id, status);
CREATE INDEX IF NOT EXISTS idx_allocations_resource_status ON allocations(resource_type, resource_id, status);
CREATE INDEX IF NOT EXISTS idx_inventory_issues_request ON inventory_issues(request_id);
CREATE INDEX IF NOT EXISTS idx_maintenance_status_date ON maintenance_records(status, scheduled_date);
CREATE INDEX IF NOT EXISTS idx_request_items_request ON request_items(request_id);